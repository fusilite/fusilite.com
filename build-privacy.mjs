// Builds <product>/privacy/index.html from that product's docs/PRIVACY.md, which stays the only copy of the policy.
// Usage: node build-privacy.mjs [cuewoven|partfinder] [path/to/PRIVACY.md]   (default: cuewoven)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const PRODUCTS = {
  cuewoven: { src: '../CueWoven/docs/PRIVACY.md', description: 'How the CueWoven browser extension handles your data: everything stays on your computer.' },
  partfinder: { src: '../partfinder/docs/PRIVACY.md', description: 'How the Part Finder browser extension handles your data: what stays in your browser and what a search sends.' },
};
const slug = process.argv[2] || 'cuewoven', product = PRODUCTS[slug];
if (!product) throw new Error(`Unknown product ${slug}; use one of ${Object.keys(PRODUCTS).join(', ')}`);
const src = process.argv[3] || new URL(product.src, import.meta.url);
const md = readFileSync(src, 'utf8').replace(/\r/g, '');

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const inline = s => esc(s)
  .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, '<a href="$2">$1</a>')
  .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
  .replace(/\*([^*]+)\*/g, '<em>$1</em>');

// shortcut: handles only the Markdown the policies use (#, ##, -, **, *, links, simple tables); extend if they grow nested lists.
const out = [];
let para = [], list = false, table = [];
const flush = () => { if (para.length) out.push(`<p>${inline(para.join(' '))}</p>`); para = []; };
const endList = () => { if (list) out.push('</ul>'); list = false; };
const cells = row => row.trim().replace(/^\||\|$/g, '').split('|').map(c => inline(c.trim()));
const endTable = () => {
  if (!table.length) return;
  const [head, ...rows] = table.filter(r => !/^\|[\s|:-]+\|$/.test(r.trim()));
  out.push(`<table><thead><tr>${cells(head).map(c => `<th>${c}</th>`).join('')}</tr></thead><tbody>${rows.map(r => `<tr>${cells(r).map(c => `<td>${c}</td>`).join('')}</tr>`).join('')}</tbody></table>`);
  table = [];
};
for (const line of md.split('\n')) {
  let m;
  if (line.startsWith('|')) { flush(); endList(); table.push(line); continue; }
  endTable();
  if ((m = line.match(/^(#{1,2}) (.*)/))) { flush(); endList(); out.push(`<h${m[1].length}>${inline(m[2])}</h${m[1].length}>`); }
  else if ((m = line.match(/^- (.*)/))) { flush(); if (!list) out.push('<ul>'); list = true; out.push(`<li>${inline(m[1])}</li>`); }
  else if (!line.trim()) { flush(); endList(); }
  else if (/^(#|```|>|\s+[-*]|\d+\. |\* )/.test(line)) throw new Error(`PRIVACY.md has Markdown this script does not convert: ${line}`);
  else { endList(); para.push(line.trim()); }
}
flush(); endList(); endTable();
const body = out.join('\n');

const title = md.match(/^# (.*)/m)?.[1];
if (!title || /\*\*|\]\(/.test(body.replace(/<a href="[^"]*"/g, ''))) throw new Error('PRIVACY.md has Markdown this script does not convert');

mkdirSync(new URL(`${slug}/privacy/`, import.meta.url), { recursive: true });
writeFileSync(new URL(`${slug}/privacy/index.html`, import.meta.url), `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(product.description)}">
<link rel="icon" href="../icon.png">
<!-- Generated by build-privacy.mjs from ${product.src.replace('../', '')}. Edit that file, not this one. -->
<style>
  :root { --bg:#faf8f4; --fg:#1d1b18; --muted:#6b655c; --line:#e6e0d6; --accent:#3d5a80; }
  @media (prefers-color-scheme: dark) {
    :root { --bg:#151412; --fg:#ece8e1; --muted:#a39d93; --line:#2e2b27; --accent:#8fb3e0; }
  }
  * { box-sizing:border-box; }
  body { margin:0; background:var(--bg); color:var(--fg); font:17px/1.6 system-ui,-apple-system,"Segoe UI",sans-serif; }
  main { max-width:760px; margin:0 auto; padding:48px 20px; overflow-wrap:anywhere; }
  nav { font-size:.95rem; margin-bottom:32px; }
  h1 { font-size:2rem; line-height:1.2; letter-spacing:-.02em; margin:0 0 8px; }
  h2 { font-size:1.2rem; margin:36px 0 8px; }
  li { margin:6px 0; }
  table { width:100%; border-collapse:collapse; font-size:.95rem; margin:12px 0; }
  th, td { text-align:left; vertical-align:top; padding:8px 10px 8px 0; border-bottom:1px solid var(--line); }
  th { font-weight:600; }
  a { color:var(--accent); }
  footer { color:var(--muted); font-size:.9rem; margin-top:48px; border-top:1px solid var(--line); padding-top:20px; }
</style>
</head>
<body>
<main>
<nav><a href="/">FusiLite Labs</a></nav>
${body}
<footer>Contact: <a href="mailto:support@fusilite.com">support@fusilite.com</a></footer>
</main>
</body>
</html>
`);
console.log(`wrote ${slug}/privacy/index.html`);
