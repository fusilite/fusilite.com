// Builds cuewoven/privacy/index.html from CueWoven's docs/PRIVACY.md, which stays the only copy of the policy.
// Usage: node build-privacy.mjs [path/to/PRIVACY.md]   (default: ../CueWoven/docs/PRIVACY.md)
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2] || new URL('../CueWoven/docs/PRIVACY.md', import.meta.url);
const md = readFileSync(src, 'utf8').replace(/\r/g, '');

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const inline = s => esc(s)
  .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, '<a href="$2">$1</a>')
  .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
  .replace(/\*([^*]+)\*/g, '<em>$1</em>');

// shortcut: handles only the Markdown PRIVACY.md uses (#, ##, -, **, *, links); extend if the policy grows tables or nested lists.
const out = [];
let para = [], list = false;
const flush = () => { if (para.length) out.push(`<p>${inline(para.join(' '))}</p>`); para = []; };
const endList = () => { if (list) out.push('</ul>'); list = false; };
for (const line of md.split('\n')) {
  let m;
  if ((m = line.match(/^(#{1,2}) (.*)/))) { flush(); endList(); out.push(`<h${m[1].length}>${inline(m[2])}</h${m[1].length}>`); }
  else if ((m = line.match(/^- (.*)/))) { flush(); if (!list) out.push('<ul>'); list = true; out.push(`<li>${inline(m[1])}</li>`); }
  else if (!line.trim()) { flush(); endList(); }
  else if (/^(\||#|```|>|\s+[-*]|\d+\. |\* )/.test(line)) throw new Error(`PRIVACY.md has Markdown this script does not convert: ${line}`);
  else { endList(); para.push(line.trim()); }
}
flush(); endList();
const body = out.join('\n');

const title = md.match(/^# (.*)/m)?.[1];
if (!title || /\*\*|\]\(/.test(body.replace(/<a href="[^"]*"/g, ''))) throw new Error('PRIVACY.md has Markdown this script does not convert');

writeFileSync(new URL('cuewoven/privacy/index.html', import.meta.url), `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="How the CueWoven browser extension handles your data: everything stays on your computer.">
<link rel="icon" href="../icon.png">
<!-- Generated by build-privacy.mjs from CueWoven/docs/PRIVACY.md. Edit that file, not this one. -->
<style>
  :root { --bg:#faf8f4; --fg:#1d1b18; --muted:#6b655c; --line:#e6e0d6; --accent:#3d5a80; }
  @media (prefers-color-scheme: dark) {
    :root { --bg:#151412; --fg:#ece8e1; --muted:#a39d93; --line:#2e2b27; --accent:#8fb3e0; }
  }
  * { box-sizing:border-box; }
  body { margin:0; background:var(--bg); color:var(--fg); font:17px/1.6 system-ui,-apple-system,"Segoe UI",sans-serif; }
  main { max-width:760px; margin:0 auto; padding:48px 20px; overflow-wrap:anywhere; }
  nav { font-size:.95rem; margin-bottom:32px; }
  h1 { font-size:2rem; line-height:1.2; letter-spacing:-.02em; margin:0 0 8px; }
  h2 { font-size:1.2rem; margin:36px 0 8px; }
  li { margin:6px 0; }
  a { color:var(--accent); }
  footer { color:var(--muted); font-size:.9rem; margin-top:48px; border-top:1px solid var(--line); padding-top:20px; }
</style>
</head>
<body>
<main>
<nav><a href="/">FusiLite Labs</a></nav>
${body}
<footer>Contact: <a href="mailto:support@fusilite.com">support@fusilite.com</a></footer>
</main>
</body>
</html>
`);
console.log('wrote cuewoven/privacy/index.html');
